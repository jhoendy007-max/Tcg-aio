export type DeskTextKey = keyof typeof TEXT.en

export function deskText(lang: MailLang, key: DeskTextKey): string {
  return TEXT[lang][key]
}

export function wizardSteps(): Array<"profile" | "account" | "task"> {
  return ["profile", "account", "task"]
}

export function wizardIssues(step: "profile" | "account" | "task", input: {
  email?: string
  phone?: string
  card?: string
  line1?: string
  city?: string
  state?: string
  zip?: string
  label?: string
  username?: string
  password?: string
  sku?: string
}, lang: MailLang): string[] {
  const issues: string[] = []
  if (step === "profile") {
    if (!input.email || !input.email.includes("@") || !input.email.includes(".")) issues.push(deskText(lang, "errEmail"))
    if (!input.phone || input.phone.replace(/\D/g, "").length < 10) issues.push(deskText(lang, "errPhone"))
    if (!input.card || input.card.replace(/\D/g, "").length < 12) issues.push(deskText(lang, "errCard"))
    if (!input.line1?.trim() || !input.city?.trim() || !input.state?.trim() || !input.zip?.trim()) issues.push(deskText(lang, "errAddress"))
  }
  if (step === "account") {
    if (!input.label?.trim() || !input.username?.includes("@") || !input.password?.trim()) issues.push(deskText(lang, "errAccount"))
  }
  if (step === "task" && !input.sku?.trim()) issues.push(deskText(lang, "errSku"))
  return issues
}
